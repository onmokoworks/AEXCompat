def path_has_traversal(path: Path) -> bool:
    return any(part in ("..", ".") for part in path.parts)


def resolve_under_root(path: Path, root: Path, *, must_exist: bool) -> Path:
    if path_has_traversal(path):
        raise ValueError("path must not contain traversal components")
    absolute = path if path.is_absolute() else LAB_ROOT / path
    resolved_root = root.resolve(strict=True)
    resolved = absolute.resolve(strict=must_exist)
    if not resolved.is_relative_to(resolved_root):
        raise ValueError(f"path must stay under {root}")
    return resolved


def validate_output_path(path: Path) -> Path:
    if path.suffix.lower() != ".json":
        raise ValueError("artifact index report must have .json extension")
    INDEX_ROOT.mkdir(parents=True, exist_ok=True)
    resolved = resolve_under_root(path, INDEX_ROOT, must_exist=False)
    resolved.parent.mkdir(parents=True, exist_ok=True)
    if not resolved.parent.resolve(strict=True).is_relative_to(INDEX_ROOT.resolve(strict=True)):
        raise ValueError(f"artifact index parent must stay under {INDEX_ROOT}")
    return resolved


def read_json(path: Path) -> dict[str, Any] | None:
    try:
        with path.open("r", encoding="utf-8") as handle:
            payload = json.load(handle)
    except (OSError, json.JSONDecodeError):
        return None
    return payload if isinstance(payload, dict) else None


def preferred_pattern_rank(path: Path, patterns: list[str]) -> int:
    for index, pattern in enumerate(patterns):
        if path.match(pattern):
            return len(patterns) - index
    return 0


