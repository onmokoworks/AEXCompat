def artifact_completeness_score(label: str, payload: dict[str, Any]) -> int:
    return sum(1 for field in REQUIRED_FIELDS.get(label, ()) if field in payload)


def safety_summary(payload: dict[str, Any]) -> dict[str, Any]:
    return {flag: payload.get(flag) for flag in SAFETY_FLAGS if flag in payload}


def find_candidates(label: str) -> list[dict[str, Any]]:
    spec = ARTIFACT_SPECS[label]
    root: Path = spec["root"]
    if not root.exists():
        return []
    candidates: list[dict[str, Any]] = []
    for path in root.glob("*.json"):
        payload = read_json(path)
        if payload is None:
            continue
        kind_matches = payload.get(spec["kind_key"]) == spec["kind"]
        if not kind_matches:
            continue
        pattern_rank = preferred_pattern_rank(path, spec["patterns"])
        candidates.append(
            {
                "path": path,
                "payload": payload,
                "pattern_rank": pattern_rank,
                "completeness_score": artifact_completeness_score(label, payload),
                "mtime": path.stat().st_mtime,
            }
        )
    candidates.sort(key=lambda item: (item["pattern_rank"], item["completeness_score"], item["mtime"]), reverse=True)
    return candidates


def select_artifact(label: str) -> dict[str, Any]:
    candidates = find_candidates(label)
    if not candidates:
        return {
            "label": label,
            "found": False,
            "path": None,
            "candidate_count": 0,
            "kind": ARTIFACT_SPECS[label]["kind"],
            "states": {},
            "safety_flags": {},
            "selection_reason": "missing",
        }
    selected = candidates[0]
    payload = selected["payload"]
    return {
        "label": label,
        "found": True,
        "path": str(selected["path"].resolve()),
        "candidate_count": len(candidates),
        "kind": payload.get(ARTIFACT_SPECS[label]["kind_key"]),
        "states": artifact_state(payload),
        "safety_flags": safety_summary(payload),
        "completeness_score": selected["completeness_score"],
        "selection_reason": "preferred_pattern" if selected["pattern_rank"] else "latest_matching_kind",
    }


def index_errors(selected: list[dict[str, Any]]) -> list[str]:
    errors: list[str] = []
    for item in selected:
        if not item["found"]:
            errors.append(f"{item['label']} artifact is missing")
        for flag, value in item.get("safety_flags", {}).items():
            if value is not False:
                errors.append(f"{item['label']} {flag} must be false")
    by_label = {item["label"]: item for item in selected}
    if by_label.get("safety_audit", {}).get("states", {}).get("audit_passed") is not True:
        errors.append("safety_audit audit_passed must be true")
    if by_label.get("publication_boundary", {}).get("states", {}).get("publishable_now") is not False:
        errors.append("publication_boundary publishable_now must be false")
    return errors


def build_index() -> dict[str, Any]:
    selected = [select_artifact(label) for label in ARTIFACT_SPECS]
    errors = index_errors(selected)
    return {
        "schema_version": 1,
        "publication_status": "local-only",
        "report_kind": "aex_artifact_index",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "index_state": "canonical_chain_indexed" if not errors else "canonical_chain_incomplete",
        "artifact_count": len(selected),
        "found_count": sum(1 for item in selected if item["found"]),
        "artifacts": selected,
        "errors": errors,
        "native_load_enabled": False,
        "native_load_performed": False,
        "dll_load_performed": False,
        "render_performed": False,
        "ae_invoked": False,
        "ofx_route_invoked": False,
        "private_payload_copied": False,
        "aex_file_opened": False,
        "notes": [
            "Index reads JSON artifacts only.",
            "Preferred real-run artifacts are selected by kind and ae/scattermap filename patterns.",
            "No AEX, AE, OFX, image runtime, or binary-payload operation is performed.",
        ],
    }


def write_json_create_new(path: Path, payload: dict[str, Any]) -> Path:
    resolved = validate_output_path(path)
    with resolved.open("x", encoding="utf-8", newline="\n") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    return resolved


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build local AEX Compat Lab artifact index")
    parser.add_argument("--out", required=True, help="Create-new artifact index under target/artifact-index")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    index = build_index()
    written = write_json_create_new(Path(args.out), index)
    print(written)
    return 0


